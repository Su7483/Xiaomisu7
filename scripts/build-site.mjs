/* 组装「可以直接上传」的静态站点目录 public/。

   只拷贝浏览器真正需要的文件：两个页面、样式、脚本、dist/（bundle + Draco
   解码器）、assets/（车模 + 分享图）。node_modules / src / server.mjs 这类
   开发期文件不进产物，否则上传体积会从 7MB 变成 60MB+。

   入口页是 index.html（极简一屏版），experience.html 是三维体验版，
   两个页面互相有链接。 */

import { cp, mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';

const ROOT = process.cwd();
const OUT = resolve(ROOT, 'public');
const MARKER = '.su7-site-build';

/* 安全闸：只允许在项目内创建/删除 public/，并且它必须是我们生成过的目录 */
if (!OUT.startsWith(ROOT + sep)) {
  throw new Error('拒绝操作项目目录之外的位置：' + OUT);
}

const FILES = ['index.html', 'styles.css', 'main.js', 'experience.html', 'experience.css'];
/* 目录名刻意避开 dist / build 这类常见构建产物名：
   Netlify Drop 会把它们当作构建输出直接忽略，导致页面上线后 404 拿不到脚本。 */
const DIRS = ['runtime', 'assets'];

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

if (await exists(OUT)) {
  const entries = await readdir(OUT);
  const ours = entries.length === 0 || entries.includes(MARKER);
  if (!ours) {
    throw new Error(
      'public/ 里已有其他内容，且不是本脚本生成的。请先确认并自行清理，脚本不会替你删除。'
    );
  }
  // 只清内容、不删目录：Explorer 打开着 public 时目录句柄会被占用，
  // 直接 rmdir 会 EBUSY，清空子项则不受影响。
  for (const entry of entries) {
    await rm(join(OUT, entry), { recursive: true, force: true });
  }
}

await mkdir(OUT, { recursive: true });

for (const file of FILES) {
  if (!(await exists(join(ROOT, file)))) throw new Error('缺少文件：' + file);
  await cp(join(ROOT, file), join(OUT, file));
}

for (const dir of DIRS) {
  if (!(await exists(join(ROOT, dir)))) throw new Error('缺少目录：' + dir);
  await cp(join(ROOT, dir), join(OUT, dir), {
    recursive: true,
    // 开发用的说明文件不进产物（assets/README.txt 里写着内部调参细节）
    filter: (src) => !/README(\.[a-z]+)?$/i.test(src),
  });
}

/* GitHub Pages 会跑 Jekyll，下划线开头的文件会被忽略，用这个关掉 */
await writeFile(join(OUT, '.nojekyll'), '');
await writeFile(join(OUT, MARKER), 'generated by scripts/build-site.mjs\n');

/* Netlify 用的响应头（Vercel 读根目录的 vercel.json） */
await writeFile(
  join(OUT, '_headers'),
  [
    '/runtime/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '/assets/*',
    '  Cache-Control: public, max-age=604800',
    '/runtime/draco/*.wasm',
    '  Content-Type: application/wasm',
    '',
  ].join('\n')
);

/* 体积统计 */
let total = 0;
const rows = [];
async function walk(dir, prefix) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(full, prefix);
    } else {
      const info = await stat(full);
      total += info.size;
      rows.push([full.slice(OUT.length + 1), info.size]);
    }
  }
}
await walk(OUT, '');
rows.sort((a, b) => b[1] - a[1]);

console.log('');
console.log('  可部署目录：' + OUT);
console.log('');
for (const [name, size] of rows) {
  console.log('   ' + (size / 1024).toFixed(0).padStart(6) + ' KB  ' + name);
}
console.log('   ' + '─'.repeat(30));
console.log('   ' + (total / 1024 / 1024).toFixed(2).padStart(6) + ' MB  合计');
console.log('');
